#pragma once

// Public C++ API surface for the Omniverse Object Delta Format (OODF) FFI.
//
// Every type used on the FFI boundary (`OwnedDelta`, `StructCommand`,
// `ParseResult`, etc.) is declared as a cxx *shared struct* in the
// `#[cxx::bridge]` module at `oodf-ffi/src/bridge.rs`. cxx-build emits the
// matching C++ definitions into the generated header included below; this
// header re-exports them under `namespace oodf` and adds the two top-level
// functions that cross the FFI boundary.
//
// The Rust-side Task 3.2 deliberately picked shared structs over ExternType
// because (a) cxx cannot return a C++-defined struct with non-trivial
// destructors by value (rust::String / rust::Vec have destructors), and
// (b) shared structs give us a single source of truth on both sides.

#include "rust/cxx.h"

// Generated by cxx-build from `oodf-ffi/src/bridge.rs`. Every shared struct
// (CommandCreateSection, StructCommand, OwnedDelta, ParseResult, …) and
// shared enum (CommandTag, ParseErrorKind) lands in namespace `oodf` here.
#include "oodf-ffi/src/bridge.rs.h"

namespace oodf {

// Parse an OODF FlatBuffers byte stream into an owned delta. Never throws.
ParseResult parse_delta(rust::Slice<const uint8_t> bytes);

// Build an OODF FlatBuffers byte stream from an owned delta. Never throws,
// never aborts: every error path (bad CommandTag from a buggy bridge caller,
// std::bad_alloc from the FlatBufferBuilder, any other escaping std::
// exception) flows back across the bridge as a `BuildResult` with `error !=
// Ok`. Previously a bad tag or OOM triggered `std::abort()`, which tore down
// every concurrent in-flight RPC sharing the process (b.vvs item 8).
BuildResult build_delta(const OwnedDelta& delta);

}  // namespace oodf
