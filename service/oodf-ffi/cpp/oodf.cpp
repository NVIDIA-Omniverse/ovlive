// Parse an untrusted OODF byte slice into an owned, plain-data delta.
//
// SECURITY INVARIANT (stated in full in this file's header comment and SDD
// §8.2): this function MUST run
// `OmniObjectDelta::VerifyDeltaBuffer` on the input BEFORE touching any
// FlatBuffers accessor (e.g. `GetDelta`, `delta->isDiff()`,
// `delta->structCommands()`). Byte-slice sanity checks and an optional magic
// probe run first, then the entry-count probe, then the verifier, then — and
// only then — we read the root table through the generated accessors. The
// entry-count probe is the one step before the verifier that reads inside the
// buffer, and it reads only what the library's own verify primitives have
// bounds-checked first (see `probe_entry_counts`). Any reordering of those
// steps is a security regression.
ParseResult parse_delta(rust::Slice<const uint8_t> bytes) {
    try {
        const uint8_t* const data = bytes.data();
        const size_t size = bytes.size();

        // Pre-verifier sanity checks: these only inspect raw byte-slice state,
        // no FlatBuffers accessor is invoked.
        if (size == 0) {
            return make_error(ParseErrorKind::EmptyInput, "input buffer is empty");
        }
        // Defensive null-pointer guard (b.vvs item 1). A `size > 0` slice
        // with a null `data` pointer would crash the first byte-read below.
        // cxx's `rust::Slice` constructor allows the (nullptr, N>0) shape, so
        // checking explicitly is cheaper than relying on accessor crashes —
        // and lets us produce a typed error instead of a SIGSEGV.
        if (data == nullptr) {
            return make_error(
                ParseErrorKind::EmptyInput,
                "input buffer pointer is null despite non-zero size");
        }
        if (size < kMinFlatBufferHeader) {
            return make_error(
                ParseErrorKind::TooShort,
                "input buffer is " + std::to_string(size) +
                    " bytes; minimum FlatBuffers header is " +
                    std::to_string(kMinFlatBufferHeader) + " bytes");
        }

        // Optional magic probe. `BufferHasIdentifier` only reads four bytes at
        // a fixed offset after the root uoffset — a bounded, non-recursive
        // scan that does not follow any untrusted offsets, so it is safe to
        // call before the full verifier. Gating here gives a more specific
        // error kind than letting the verifier reject the buffer.
        if (!OmniObjectDelta::DeltaBufferHasIdentifier(data)) {
            return make_error(
                ParseErrorKind::BadMagic,
                "buffer does not carry the \"OODF\" file_identifier");
        }

        // Entry-count probe, before the verifier. A delta whose struct
        // commands + set fields + time samples exceed `kMaxDeltaEntries` is
        // refused here in O(1) with the three counts and the limit as
        // structured fields, so the caller can say exactly why and by how
        // much — the verifier's own table-cap failure records no cause. A
        // buffer the probe cannot read falls through to the verifier with
        // its outcome unchanged.
        {
            EntryCounts counts;
            if (probe_entry_counts(data, size, &counts)) {
                const uint64_t total =
                    counts.struct_commands + counts.set_fields + counts.time_samples;
                if (total > kMaxDeltaEntries) {
                    ParseResult result = make_error(
                        ParseErrorKind::TooManyTables,
                        "delta carries " + std::to_string(total) +
                            " entries; at most " + std::to_string(kMaxDeltaEntries) +
                            " fit in one delta");
                    result.struct_command_count = counts.struct_commands;
                    result.set_field_count = counts.set_fields;
                    result.time_sample_count = counts.time_samples;
                    result.max_entries = kMaxDeltaEntries;
                    return result;
                }
            }
        }

        // Run the hardened verifier with tightened bounds (b.vvs item 2).
        // The default FlatBuffers Verifier limits (max_depth = 64,
        // max_tables = 1_000_000) leave room for a 100 MB payload claiming
        // millions of nested tables to keep the verifier busy. The OODF
        // schema's maximum legal nesting is 3 levels, so we cap depth at 8
        // (margin for future schema growth) and tables at 100 K. An over-cap
        // delta has normally been refused by the probe above already; this
        // cap is the backstop for a buffer the probe could not count, which
        // the verifier rejects without walking past the cap.
        ::flatbuffers::Verifier::Options verifier_opts;
        verifier_opts.max_depth = kVerifierMaxDepth;
        verifier_opts.max_tables = kVerifierMaxTables;
        ::flatbuffers::Verifier verifier(data, size, verifier_opts);
        if (!OmniObjectDelta::VerifyDeltaBuffer(verifier)) {
            return make_error(
                ParseErrorKind::VerifierFailed,
                "FlatBuffers verifier rejected a " + std::to_string(size) +
                    "-byte OODF buffer");
        }

        // OMPF framing strips any size prefix before handing bytes to the
        // FFI, so use the non-prefixed accessor. From this point on,
        // accessor calls on the verified buffer are memory-safe.
        const OmniObjectDelta::Delta* delta = OmniObjectDelta::GetDelta(data);
        if (delta == nullptr) {
            return make_error(
                ParseErrorKind::InternalError,
                "GetDelta returned null after successful verification");
        }

        ParseResult result{};
        result.delta.is_diff = delta->isDiff();
        result.delta.base_version = delta->baseVersion();
        // Explicit UTF-8 pre-check on every string field. The FlatBuffers
        // verifier treats strings as opaque byte vectors and does not
        // validate UTF-8, so a verifier-valid buffer can still carry bytes
        // that would cause `rust::String`'s throwing constructor to throw
        // and escape the function. Validating here returns a typed error
        // before any `rust::String` is constructed.
        {
            ParseResult err_result{};
            if (!check_utf8_or_error(delta->sourceFormat(), "sourceFormat", &err_result)) {
                return err_result;
            }
        }
        result.delta.source_format = to_rust_string(delta->sourceFormat());

        // ── Walk structCommands + structCommands_type in parallel ───────
        // The flatc-generated `VerifyStructCommandVector` (invoked by
        // `Delta::Verify`) has already confirmed that both vectors exist
        // together or are both absent, have equal size, and that every
        // payload offset points to a well-formed table of the type named by
        // its discriminant. The loop below therefore only needs to dispatch
        // on the discriminant and populate plain-data fields.
        const auto* cmd_types = delta->structCommands_type();
        const auto* cmd_values = delta->structCommands();
        if (cmd_types != nullptr && cmd_values != nullptr) {
            const auto count = cmd_values->size();
            // Defensive cap on attacker-controlled count (b.vvs item 3).
            // The verifier only checks that each per-element offset fits
            // inside the buffer — a million-element vector inside a 100 MB
            // payload is verifier-valid. Without a cap, the previous
            // `result.delta.struct_commands.reserve(count)` would commit
            // ~96 MB up front (StructCommand is ~96 bytes after cxx layout)
            // per parse. Drop the eager `reserve` — amortized growth via
            // `push_back` is fine for legitimate sizes and disarms the
            // worst case for malicious sizes.
            if (count > kMaxCommands) {
                return make_error(
                    ParseErrorKind::VerifierFailed,
                    "structCommands vector size " + std::to_string(count) +
                        " exceeds the defensive cap of " +
                        std::to_string(kMaxCommands));
            }
            for (::flatbuffers::uoffset_t i = 0; i < count; ++i) {
                const auto type_raw = cmd_types->Get(i);
                const auto type = static_cast<OmniObjectDelta::StructCommand>(type_raw);
                const void* payload = cmd_values->Get(i);
                StructCommand out{};
                switch (type) {
                    case OmniObjectDelta::StructCommand_CommandCreateSection: {
                        const auto* c =
                            static_cast<const OmniObjectDelta::CommandCreateSection*>(payload);
                        ParseResult err_result{};
                        if (!check_utf8_or_error(
                                c->sectionName(),
                                "CommandCreateSection.sectionName",
                                &err_result)) {
                            return err_result;
                        }
                        out.tag = CommandTag::CreateSection;
                        out.create_section.parent_id = c->parentId();
                        out.create_section.section_id = c->sectionId();
                        out.create_section.section_name = to_rust_string(c->sectionName());
                        out.create_section.section_type = c->sectionType();
                        break;
                    }
                    case OmniObjectDelta::StructCommand_CommandDeleteSection: {
                        const auto* c =
                            static_cast<const OmniObjectDelta::CommandDeleteSection*>(payload);
                        out.tag = CommandTag::DeleteSection;
                        out.delete_section.parent_id = c->parentId();
                        out.delete_section.section_id = c->sectionId();
                        break;
                    }
                    case OmniObjectDelta::StructCommand_CommandMoveSection: {
                        const auto* c =
                            static_cast<const OmniObjectDelta::CommandMoveSection*>(payload);
                        ParseResult err_result{};
                        if (!check_utf8_or_error(
                                c->newName(),
                                "CommandMoveSection.newName",
                                &err_result)) {
                            return err_result;
                        }
                        out.tag = CommandTag::MoveSection;
                        out.move_section.old_parent_id = c->oldParentId();
                        out.move_section.new_parent_id = c->newParentId();
                        out.move_section.section_id = c->sectionId();
                        out.move_section.new_name = to_rust_string(c->newName());
                        break;
                    }
                    case OmniObjectDelta::StructCommand_CommandReorderChildren: {
                        const auto* c =
                            static_cast<const OmniObjectDelta::CommandReorderChildren*>(payload);
                        // Defensive cap on the children-list vector size
                        // (b.vvs item 3). A million-element verifier-valid
                        // children list would copy ~8 MB per ReorderChildren
                        // — and a hostile buffer is free to repeat the shape
                        // across many ReorderChildren commands. Apply the
                        // same `kMaxCommands` ceiling here. Refused as the
                        // typed `ChildrenListTooLong`, its length in
                        // `children_list_len`, so the caller can answer it
                        // as the over-long list it is (the service's
                        // `CHILDREN_LIST_TOO_LONG`) rather than as a
                        // malformed buffer.
                        if (const auto* children = c->childrenList()) {
                            if (children->size() > kMaxCommands) {
                                ParseResult result = make_error(
                                    ParseErrorKind::ChildrenListTooLong,
                                    "ReorderChildren.childrenList size " +
                                        std::to_string(children->size()) +
                                        " exceeds the defensive cap of " +
                                        std::to_string(kMaxCommands));
                                result.children_list_len = children->size();
                                return result;
                            }
                        }
                        out.tag = CommandTag::ReorderChildren;
                        out.reorder_children.section_id = c->sectionId();
                        out.reorder_children.children_list_id = c->childrenListId();
                        out.reorder_children.children_list = to_rust_u64_vec(c->childrenList());
                        break;
                    }
                    case OmniObjectDelta::StructCommand_CommandDiffChangeSection: {
                        const auto* c =
                            static_cast<const OmniObjectDelta::CommandDiffChangeSection*>(payload);
                        ParseResult err_result{};
                        if (!check_utf8_or_error(
                                c->sectionName(),
                                "CommandDiffChangeSection.sectionName",
                                &err_result)) {
                            return err_result;
                        }
                        out.tag = CommandTag::DiffChangeSection;
                        out.diff_change_section.parent_id = c->parentId();
                        out.diff_change_section.section_id = c->sectionId();
                        out.diff_change_section.section_name = to_rust_string(c->sectionName());
                        out.diff_change_section.section_type = c->sectionType();
                        out.diff_change_section.section_order = c->sectionOrder();
                        break;
                    }
                    case OmniObjectDelta::StructCommand_CommandDiffDeleteSection: {
                        const auto* c =
                            static_cast<const OmniObjectDelta::CommandDiffDeleteSection*>(payload);
                        out.tag = CommandTag::DiffDeleteSection;
                        out.diff_delete_section.section_id = c->sectionId();
                        break;
                    }
                    case OmniObjectDelta::StructCommand_NONE:
                    default: {
                        // Two cases, collapsed because the outcome is identical:
                        // (1) `NONE` is valid FlatBuffers union syntax for "no
                        //     payload", but OODF never encodes it — upstream
                        //     producers always pair a discriminant with a real
                        //     payload. A NONE here is therefore a malformed
                        //     buffer that slipped past the verifier's per-slot
                        //     check only because the verifier accepts NONE as
                        //     a legal union value. (2) `default:` catches any
                        //     out-of-range u8 the verifier also accepts (e.g.
                        //     tag 7 in a schema with tags 1..=6 — see
                        //     `error_unknown_command_type_discriminant`).
                        // Both are reported as `UnknownCommandType` with the
                        // observed discriminant and its index in the vector.
                        return make_error(
                            ParseErrorKind::UnknownCommandType,
                            "unknown StructCommand discriminant " +
                                std::to_string(static_cast<unsigned>(type_raw)) +
                                " at index " + std::to_string(i));
                    }
                }
                result.delta.struct_commands.push_back(std::move(out));
            }
        }

        // ── setFields ────────────────────────────────────────────────────
        if (const auto* fields = delta->setFields()) {
            // Same defensive cap + drop-reserve as struct_commands above
            // (b.vvs item 3). `SetField` is ~80 bytes after cxx layout, so
            // a million-element vector would commit ~80 MB up front
            // without this guard.
            const auto fields_count = fields->size();
            if (fields_count > kMaxCommands) {
                return make_error(
                    ParseErrorKind::VerifierFailed,
                    "setFields vector size " + std::to_string(fields_count) +
                        " exceeds the defensive cap of " +
                        std::to_string(kMaxCommands));
            }
            for (::flatbuffers::uoffset_t i = 0; i < fields_count; ++i) {
                const auto* f = fields->Get(i);
                ParseResult err_result{};
                if (!check_utf8_or_error(
                        f->keyName(),
                        "SetField.keyName",
                        &err_result)) {
                    return err_result;
                }
                SetField sf{};
                sf.section_id = f->sectionId();
                sf.key_name = to_rust_string(f->keyName());
                sf.value_or_ext_hash = to_rust_byte_vec(f->valueOrExtHash());
                sf.ext_value_size = f->extValueSize();
                sf.ext_value_index = f->extValueIndex();
                sf.set_order = f->setOrder();
                result.delta.set_fields.push_back(std::move(sf));
            }
        }

        // ── timeSamples ──────────────────────────────────────────────────
        if (const auto* samples = delta->timeSamples()) {
            // Same defensive cap + drop-reserve as struct_commands and
            // set_fields above (b.vvs item 3).
            const auto samples_count = samples->size();
            if (samples_count > kMaxCommands) {
                return make_error(
                    ParseErrorKind::VerifierFailed,
                    "timeSamples vector size " + std::to_string(samples_count) +
                        " exceeds the defensive cap of " +
                        std::to_string(kMaxCommands));
            }
            for (::flatbuffers::uoffset_t i = 0; i < samples_count; ++i) {
                const auto* t = samples->Get(i);
                TimeSample ts{};
                ts.section_id = t->sectionId();
                ts.time = t->time();
                ts.value_or_ext_hash = to_rust_byte_vec(t->valueOrExtHash());
                ts.ext_value_size = t->extValueSize();
                ts.ext_value_index = t->extValueIndex();
                result.delta.time_samples.push_back(std::move(ts));
            }
        }

        result.error = ParseErrorKind::Ok;
        result.error_message = rust::String();
        return result;
    } catch (const std::bad_alloc&) {
        return make_error(ParseErrorKind::AllocationFailed,
                          "parse_delta: std::bad_alloc");
    } catch (const std::exception& e) {
        return make_error(ParseErrorKind::InternalError,
                          std::string("parse_delta: std::exception: ") + e.what());
    } catch (...) {
        return make_error(ParseErrorKind::InternalError,
                          "parse_delta: non-std::exception thrown");
    }
}

// Serialize an OwnedDelta into an OODF FlatBuffers byte stream.
//
// b.vvs item 8: this function used to be advertised as infallible and called
// `std::abort()` on an unknown `CommandTag` or `std::bad_alloc`. Both shapes
// can be triggered from a bridge caller (the cxx bridge admits raw
// `repr: u8`), so an abort tore down every concurrent in-flight RPC sharing
// the process. The result type is now `BuildResult` — error values flow back
// across the bridge so the Rust side can surface them as a clean
// `OodfError` to the offending caller without affecting the rest of the
// process.
//
// Hot-path note (b.vvs item 5): every per-`SetField` / per-`TimeSample` /
// per-`ReorderChildren` byte vector is now written directly into the
// FlatBuffers builder via `CreateVector(data, size)`. The previous code
// constructed an intermediate `std::vector<uint8_t> value(begin, end)` for
// each value and then handed the vector to `CreateVector` — for a single
// 100 MB ext-value commit that added a 100 MB copy on top of the
// unavoidable copy into the FlatBuffers arena. Skipping the intermediate
// halves total bytes moved on the build hot path.
BuildResult build_delta(const OwnedDelta& delta) {
    try {
        ::flatbuffers::FlatBufferBuilder builder;

        // Parallel vectors mirroring the split-vtable layout that the legacy
        // C++ live-edit service emits: one uint8_t discriminant per command,
        // one Offset<void> payload per command.
        std::vector<uint8_t> cmd_types;
        std::vector<::flatbuffers::Offset<void>> cmd_values;
        cmd_types.reserve(delta.struct_commands.size());
        cmd_values.reserve(delta.struct_commands.size());

        size_t struct_cmd_index = 0;
        for (const StructCommand& sc : delta.struct_commands) {
            switch (sc.tag) {
                case CommandTag::CreateSection: {
                    const auto& c = sc.create_section;
                    auto name = builder.CreateString(
                        c.section_name.data(), c.section_name.size());
                    auto off = OmniObjectDelta::CreateCommandCreateSection(
                        builder,
                        c.parent_id,
                        c.section_id,
                        name,
                        c.section_type);
                    cmd_types.push_back(OmniObjectDelta::StructCommand_CommandCreateSection);
                    cmd_values.push_back(off.Union());
                    break;
                }
                case CommandTag::DeleteSection: {
                    const auto& c = sc.delete_section;
                    auto off = OmniObjectDelta::CreateCommandDeleteSection(
                        builder,
                        c.parent_id,
                        c.section_id);
                    cmd_types.push_back(OmniObjectDelta::StructCommand_CommandDeleteSection);
                    cmd_values.push_back(off.Union());
                    break;
                }
                case CommandTag::MoveSection: {
                    const auto& c = sc.move_section;
                    auto name = builder.CreateString(
                        c.new_name.data(), c.new_name.size());
                    auto off = OmniObjectDelta::CreateCommandMoveSection(
                        builder,
                        c.old_parent_id,
                        c.new_parent_id,
                        c.section_id,
                        name);
                    cmd_types.push_back(OmniObjectDelta::StructCommand_CommandMoveSection);
                    cmd_values.push_back(off.Union());
                    break;
                }
                case CommandTag::ReorderChildren: {
                    const auto& c = sc.reorder_children;
                    // rust::Vec<uint64_t> → flatbuffers vector with no
                    // intermediate std::vector copy (b.vvs item 5).
                    // `rust::Vec<uint64_t>::data() + size()` is a contiguous
                    // little-endian uint64_t buffer — the same on-wire layout
                    // FlatBuffers expects — so `CreateVector(data, size)`
                    // builds the FlatBuffers vector with exactly one bulk
                    // copy into the arena.
                    auto children_off = builder.CreateVector<uint64_t>(
                        c.children_list.data(), c.children_list.size());
                    auto off = OmniObjectDelta::CreateCommandReorderChildren(
                        builder,
                        c.section_id,
                        c.children_list_id,
                        children_off);
                    cmd_types.push_back(OmniObjectDelta::StructCommand_CommandReorderChildren);
                    cmd_values.push_back(off.Union());
                    break;
                }
                case CommandTag::DiffChangeSection: {
                    const auto& c = sc.diff_change_section;
                    auto name = builder.CreateString(
                        c.section_name.data(), c.section_name.size());
                    auto off = OmniObjectDelta::CreateCommandDiffChangeSection(
                        builder,
                        c.parent_id,
                        c.section_id,
                        name,
                        c.section_type,
                        c.section_order);
                    cmd_types.push_back(OmniObjectDelta::StructCommand_CommandDiffChangeSection);
                    cmd_values.push_back(off.Union());
                    break;
                }
                case CommandTag::DiffDeleteSection: {
                    const auto& c = sc.diff_delete_section;
                    auto off = OmniObjectDelta::CreateCommandDiffDeleteSection(
                        builder,
                        c.section_id);
                    cmd_types.push_back(OmniObjectDelta::StructCommand_CommandDiffDeleteSection);
                    cmd_values.push_back(off.Union());
                    break;
                }
                case CommandTag::NONE:
                default: {
                    // Invalid per the OwnedDelta contract documented in
                    // oodf.h: the idiomatic Rust types never synthesize
                    // NONE or values outside the declared enum. Reaching
                    // here means a bridge caller smuggled a raw out-of-
                    // range `repr: u8` (`#[repr(u8)]` shared enums are
                    // wire-typed as `u8` and the bridge accepts any value).
                    // Surface as a typed error instead of `std::abort()`
                    // (b.vvs item 8) so the offending caller can be told
                    // off without taking down every other in-flight RPC.
                    return make_build_error(
                        BuildErrorKind::UnknownCommandTag,
                        "build_delta: unknown CommandTag discriminant " +
                            std::to_string(
                                static_cast<unsigned>(
                                    static_cast<uint8_t>(sc.tag))) +
                            " at struct_commands index " +
                            std::to_string(struct_cmd_index));
                }
            }
            ++struct_cmd_index;
        }

        // Order is significant for all three vectors — do NOT sort.
        auto struct_cmds_type_off = builder.CreateVector<uint8_t>(cmd_types);
        auto struct_cmds_off =
            builder.CreateVector<::flatbuffers::Offset<void>>(cmd_values);

        std::vector<::flatbuffers::Offset<OmniObjectDelta::SetField>> set_field_offsets;
        set_field_offsets.reserve(delta.set_fields.size());
        for (const SetField& f : delta.set_fields) {
            auto key = builder.CreateString(f.key_name.data(), f.key_name.size());
            // Direct CreateVector(data, size) — drop the redundant
            // std::vector<uint8_t> copy (b.vvs item 5). For a 100 MB
            // ext-value commit this halves bytes moved on the build hot
            // path; the only remaining copy is the unavoidable copy into
            // the FlatBuffers builder arena.
            auto value_off = builder.CreateVector<uint8_t>(
                f.value_or_ext_hash.data(), f.value_or_ext_hash.size());
            auto off = OmniObjectDelta::CreateSetField(
                builder,
                f.section_id,
                key,
                value_off,
                f.ext_value_size,
                f.ext_value_index,
                f.set_order);
            set_field_offsets.push_back(off);
        }
        auto set_fields_off = builder.CreateVector<
            ::flatbuffers::Offset<OmniObjectDelta::SetField>>(set_field_offsets);

        std::vector<::flatbuffers::Offset<OmniObjectDelta::TimeSample>> time_sample_offsets;
        time_sample_offsets.reserve(delta.time_samples.size());
        for (const TimeSample& t : delta.time_samples) {
            // Same b.vvs item 5 fix as SetField: write directly to the
            // FlatBuffers arena instead of through an intermediate
            // std::vector<uint8_t>.
            auto value_off = builder.CreateVector<uint8_t>(
                t.value_or_ext_hash.data(), t.value_or_ext_hash.size());
            auto off = OmniObjectDelta::CreateTimeSample(
                builder,
                t.section_id,
                t.time,
                value_off,
                t.ext_value_size,
                t.ext_value_index);
            time_sample_offsets.push_back(off);
        }
        auto time_samples_off = builder.CreateVector<
            ::flatbuffers::Offset<OmniObjectDelta::TimeSample>>(time_sample_offsets);

        auto source_format_off = builder.CreateString(
            delta.source_format.data(), delta.source_format.size());

        auto delta_off = OmniObjectDelta::CreateDelta(
            builder,
            delta.is_diff,
            delta.base_version,
            struct_cmds_type_off,
            struct_cmds_off,
            set_fields_off,
            time_samples_off,
            source_format_off);

        // FinishDeltaBuffer writes the "OODF" file_identifier at bytes 4–7
        // (immediately after the root uoffset_t) — this is the wire contract
        // parse_delta's BufferHasIdentifier check relies on.
        OmniObjectDelta::FinishDeltaBuffer(builder, delta_off);

        // Copy the finished buffer out in one bulk-copy bridge call.
        // GetBufferPointer/GetSize point into the builder's internal arena,
        // which is destroyed on scope exit, so a fresh rust::Vec<uint8_t>
        // is required. The previous byte-by-byte loop incurred one
        // reserve_total bridge call per byte; extend_byte_vec collapses
        // that into a single bridge call that delegates to Rust's
        // `Vec::extend_from_slice` (b.8uk). Measurable speedup on 1 MB+
        // payloads.
        const uint8_t* const buf_ptr = builder.GetBufferPointer();
        const size_t buf_size = builder.GetSize();

        // Defensive guard (b.vvs item 1) on the final copy-out: if the
        // builder somehow returned a non-zero size but a null pointer (the
        // FlatBufferBuilder API contract guarantees this is impossible
        // after a successful Finish — but defending here is cheap and
        // turns any future regression into a typed error instead of an
        // unbounded read).
        if (buf_size > 0 && buf_ptr == nullptr) {
            return make_build_error(
                BuildErrorKind::InternalError,
                "build_delta: FlatBufferBuilder returned null pointer with size " +
                    std::to_string(buf_size));
        }

        BuildResult result{};
        if (buf_size > 0) {
            extend_byte_vec(result.bytes, rust::Slice<const uint8_t>(buf_ptr, buf_size));
        }
        result.error = BuildErrorKind::Ok;
        result.error_message = rust::String();
        return result;
    } catch (const std::bad_alloc&) {
        // Replaces a former std::abort() — see b.vvs item 8. Surfacing as
        // data lets the Rust side fail one RPC instead of every concurrent
        // in-flight RPC sharing the process.
        return make_build_error(
            BuildErrorKind::AllocationFailed,
            "build_delta: std::bad_alloc");
    } catch (const std::exception& e) {
        return make_build_error(
            BuildErrorKind::InternalError,
            std::string("build_delta: std::exception: ") + e.what());
    } catch (...) {
        return make_build_error(
            BuildErrorKind::InternalError,
            "build_delta: non-std::exception thrown");
    }
}

