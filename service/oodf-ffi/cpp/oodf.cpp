// Minimum viable FlatBuffers header: 4-byte root uoffset_t + 4-byte file
// identifier. Any buffer smaller than this cannot even contain the fixed-
// width preamble that `BufferHasIdentifier` reads, so we reject it with a
// dedicated `TooShort` error before invoking the verifier. This threshold
// is deliberately conservative — a real OODF root table with vtable and
// scalar fields is always well above 12 bytes, so the verifier will reject
// anything in the 8..~20-byte range that slips through. Keeping the floor
// at the preamble boundary avoids entangling this check with schema-
// specific minimum sizes.
constexpr size_t kMinFlatBufferHeader = 8;

// ── Verifier::Options bounds (b.vvs item 2) ────────────────────────────────
// The FlatBuffers verifier walks the buffer recursively. The library
// defaults (max_depth = 64, max_tables = 1_000_000) are far looser than
// anything the OODF schema can legitimately produce:
//
//   * Maximum legal nesting: Delta → vector<StructCommand> → CommandFoo → ...
//     The deepest OODF schema branch (`CommandCreateSection` and friends)
//     bottoms out at 3 levels of table nesting; setting `max_depth = 8`
//     leaves a generous safety margin against future schema growth while
//     rejecting hostile inputs that fan a deep table chain to OOM the
//     verifier stack.
//
//   * Maximum tables: the verifier counts every table it visits, and the
//     OODF schema has no nested tables, so a delta is exactly 1 (root) +
//     struct commands + set fields + time samples tables. Size in bytes says
//     little about that count: a 9 MB delta has been measured at 151,093
//     tables. A payload claiming 1 M tables is a DoS shape: the verifier
//     would walk every one of them before rejection. Capping at 100_000
//     bounds verifier work to a few-millisecond budget on a well-formed
//     buffer.
//
// Order of the checks in `parse_delta`: the entry-count probe runs before the
// verifier (see `probe_entry_counts`) and refuses a buffer whose three
// vectors sum to more than `kMaxDeltaEntries` with `TooManyTables`, carrying
// the counts, in O(1) and before the verifier walks a single command. The verifier's
// `max_tables` cap stays as the backstop: a buffer the probe cannot read
// (malformed root or vector header, unpaired union vectors) falls through to
// the verifier unchanged, which still rejects it or bounds its walk.
//
// These limits are documented as the contract for what callers of
// `parse_delta` may rely on. Bumping them, or adding a read before the
// verifier, is allowed but requires a security review. `kVerifierMaxTables`
// must equal the Rust constant `oodf_ffi::MAX_DELTA_TABLES` (`src/lib.rs`),
// which the service derives its per-delta entry limit from; change both
// together.
constexpr size_t kVerifierMaxDepth = 8;
constexpr size_t kVerifierMaxTables = 100'000;

// The most entries (struct commands + set fields + time samples, summed)
// one delta may carry: the verifier's table cap less the root table.
constexpr size_t kMaxDeltaEntries = kVerifierMaxTables - 1;

// ── Per-vector reservation cap (b.vvs item 3) ──────────────────────────────
// The FlatBuffers verifier accepts any vector whose declared size fits
// within the buffer. A million-element `structCommands` vector inside an
// otherwise compact buffer survives verification because the verifier only
// validates per-element offsets, not the *amortized* allocation cost on
// the consumer side. `StructCommand` is ~96 bytes after cxx layout, so
// blindly doing `reserve(cmd_values->size())` would commit ~96 MB up front
// for every parse — a DoS shape independent of how much real data the
// buffer carries.
//
// `kMaxCommands` is a defense-in-depth ceiling. For the three table vectors
// it is unreachable today — the entry-count probe and the verifier's table
// cap already hold their sum under `kMaxDeltaEntries` — so it only matters if
// those bounds are ever loosened. For the per-`ReorderChildren` children
// list (a `[ulong]` vector, which the verifier does not count as tables) it
// is the operative bound in the parser, ten times the service's own 100,000-id
// limit on one list. A table vector above the cap returns `VerifierFailed`, and
// a children list above it `ChildrenListTooLong` carrying its length, rather
// than reserving or copying the requested capacity.
//
// The reserve calls themselves are deliberately dropped (amortized growth
// via `push_back` is fine for legitimate sizes; the cap removes the
// adversarial worst case).
constexpr size_t kMaxCommands = 1'000'000;

// Bridge-safe error constructor.
//
// `rust::String`'s `(const char*, size_t)` constructor throws `std::invalid_
// argument` on non-UTF-8 input. `make_error` is called on both the happy and
// unhappy paths (including from `catch` blocks), and its inputs are produced
// by this TU (e.g. std::to_string, string literals) or by `what()` on a
// standard-library exception — all of which have always been ASCII in
// practice. Use `rust::String::lossy` anyway so a hypothetical non-ASCII
// value cannot resurrect the narrow `std::terminate` path (a throw from
// inside the catch block would escape the function with no cxx-generated
// try/catch shim to intercept it — see the broad catch-all at the bottom of
// `parse_delta` / `build_delta`). Lossy replaces invalid bytes with U+FFFD
// and is noexcept, matching the "never throws" guarantee advertised in
// oodf.h.
ParseResult make_error(ParseErrorKind kind, std::string message) {
    ParseResult result{};
    result.error = kind;
    result.error_message = rust::String::lossy(message);
    return result;
}

// Counterpart of `make_error` for the build path (b.vvs item 8). Used to
// surface bad-tag / OOM / unknown-exception failures as data instead of
// `std::abort()` — see the `BuildErrorKind` taxonomy declared in
// `src/bridge.rs`. `bytes` is intentionally left empty when an error fires:
// the Rust side discards the bytes vector unless `error == Ok`.
BuildResult make_build_error(BuildErrorKind kind, std::string message) {
    BuildResult result{};
    result.error = kind;
    result.error_message = rust::String::lossy(message);
    return result;
}

// Validity check on a possibly-null FlatBuffers string: is the payload valid
// UTF-8? Returns true for a null pointer (treated as an empty string, which
// is trivially valid). On invalid UTF-8, writes the zero-based offset of the
// first bad byte into `*out_invalid_offset` so the caller can surface it in
// an error message.
//
// Implements the RFC 3629 subset of UTF-8 that Rust's `str::from_utf8`
// accepts: ASCII (1 byte), 2/3/4-byte sequences with the canonical leading-
// byte ranges, overlong forms rejected, surrogates (U+D800..U+DFFF) rejected,
// and code points above U+10FFFF rejected. The check deliberately runs on
// raw bytes rather than delegating to `rust::String`'s constructor so we can
// return a typed error instead of catching an exception.
bool is_valid_utf8(const ::flatbuffers::String* s, size_t* out_invalid_offset) {
    if (s == nullptr) {
        return true;
    }
    const unsigned char* bytes = reinterpret_cast<const unsigned char*>(s->c_str());
    const size_t len = s->size();
    size_t i = 0;
    while (i < len) {
        const unsigned char b0 = bytes[i];
        size_t extra = 0;
        unsigned int cp_min = 0;
        unsigned int cp_max = 0;
        unsigned int cp = 0;
        if (b0 < 0x80u) {
            i += 1;
            continue;
        } else if ((b0 & 0xE0u) == 0xC0u) {
            extra = 1;
            cp_min = 0x80u;
            cp_max = 0x7FFu;
            cp = b0 & 0x1Fu;
        } else if ((b0 & 0xF0u) == 0xE0u) {
            extra = 2;
            cp_min = 0x800u;
            cp_max = 0xFFFFu;
            cp = b0 & 0x0Fu;
        } else if ((b0 & 0xF8u) == 0xF0u) {
            extra = 3;
            cp_min = 0x10000u;
            cp_max = 0x10FFFFu;
            cp = b0 & 0x07u;
        } else {
            if (out_invalid_offset) {
                *out_invalid_offset = i;
            }
            return false;
        }
        if (i + extra >= len) {
            if (out_invalid_offset) {
                *out_invalid_offset = i;
            }
            return false;
        }
        for (size_t k = 1; k <= extra; ++k) {
            const unsigned char bk = bytes[i + k];
            if ((bk & 0xC0u) != 0x80u) {
                if (out_invalid_offset) {
                    *out_invalid_offset = i + k;
                }
                return false;
            }
            cp = (cp << 6) | (bk & 0x3Fu);
        }
        // Reject overlong encodings, UTF-16 surrogates, and code points
        // above U+10FFFF.
        if (cp < cp_min || cp > cp_max || (cp >= 0xD800u && cp <= 0xDFFFu)) {
            if (out_invalid_offset) {
                *out_invalid_offset = i;
            }
            return false;
        }
        i += 1 + extra;
    }
    return true;
}

// Convert a possibly-null FlatBuffers string to a non-null rust::String.
// Callers MUST have already run `is_valid_utf8` on the same pointer (either
// directly or via `check_utf8_or_error`) before reaching this helper — the
// post-check constructor therefore cannot throw. Using `rust::String::lossy`
// instead of the `(const char*, size_t)` ctor makes that guarantee explicit
// (noexcept; would substitute U+FFFD for any stray bad byte that slipped
// past the pre-check rather than throwing and climbing out through the
// broad catch-all below).
rust::String to_rust_string(const ::flatbuffers::String* s) {
    if (s == nullptr) {
        return rust::String();
    }
    return rust::String::lossy(std::string(s->c_str(), s->size()));
}

// Run `is_valid_utf8` on `s`; if it fails, build an `InvalidUtf8` ParseResult
// tagged with the schema field name. Returns `true` on success (caller may
// proceed to `to_rust_string`), `false` on failure (caller returns
// `*out_error` immediately).
// `field_name` is a `string_view` rather than `const char*` so the length
// travels with the pointer: every caller passes a literal, and carrying the
// size avoids a `strlen` over a pointer this helper cannot bounds-check.
bool check_utf8_or_error(const ::flatbuffers::String* s,
                          std::string_view field_name,
                          ParseResult* out_error) {
    size_t offset = 0;
    if (is_valid_utf8(s, &offset)) {
        return true;
    }
    std::string message;
    message.reserve(field_name.size() + 48);
    message.append(field_name);
    message.append(" contained invalid UTF-8 byte at offset ");
    message.append(std::to_string(offset));
    *out_error = make_error(ParseErrorKind::InvalidUtf8, std::move(message));
    return false;
}

// Convert a possibly-null byte vector to an owned rust::Vec<uint8_t>.
//
// External values can be megabytes, so the per-byte `push_back` that cxx's
// templated `emplace_back` translates into (one `reserve_total` bridge call
// per byte in cxx 1.0.194) adds measurable overhead on the parse path. A
// single `extend_byte_vec` bridge call invokes Rust's
// `Vec::extend_from_slice` exactly once, amortizing the bridge cost over
// the whole copy. Measured on an M-series release build: ~200 MB/s for
// the per-byte path vs ~1.8 GB/s with `extend_byte_vec` on 1 MB payloads
// (b.8uk).
//
// Defensive guard (b.vvs item 1): if the FlatBuffers vector is absent OR
// its size is zero AND data is null (which the FlatBuffers contract
// permits for empty vectors), skip the bridge call entirely. Constructing
// `rust::Slice` from `(nullptr, 0)` is technically defined behaviour in
// cxx 1.0.194 (the slice is empty) but the explicit early return keeps
// the contract clear and matches the same pattern used in
// `extend_u64_vec`'s Rust impl.
rust::Vec<uint8_t> to_rust_byte_vec(const ::flatbuffers::Vector<uint8_t>* v) {
    rust::Vec<uint8_t> out;
    if (v == nullptr) {
        return out;
    }
    const size_t size = v->size();
    if (size == 0) {
        return out;
    }
    const uint8_t* data = v->data();
    if (data == nullptr) {
        // Verifier-accepted empty vector with no backing storage.
        return out;
    }
    rust::Slice<const uint8_t> slice(data, size);
    extend_byte_vec(out, slice);
    return out;
}

// Convert a possibly-null uint64 vector to rust::Vec<uint64_t>.
//
// Routed through `extend_u64_vec` for the same reason `to_rust_byte_vec`
// routes through `extend_byte_vec`: the previous `out.reserve(v->size()) +
// per-element push_back` loop performed one bridge call per element. On a
// `CommandReorderChildren` with a one-million-element `childrenList` that
// translated into ~1 M bridge round-trips with ~1 M `reserve_total` calls,
// each crossing the FFI. The bulk-copy idiom collapses the entire copy
// into a single bridge invocation that delegates to Rust's
// `Vec::extend_from_slice` (b.vvs item 4). Same defensive null-pointer
// guard as `to_rust_byte_vec` (b.vvs item 1).
//
// Alignment note: `flatbuffers::Vector<uint64_t>::data()` is documented as
// returning natively-aligned data, but the FlatBuffers wire layout (a
// uint32_t length prefix followed by elements) means the C++-side pointer
// can fall on a 4-byte boundary inside a 4-byte-aligned host buffer when
// the embedding buffer is itself not 8-byte aligned (cxx's
// `rust::Vec<u8>::data()` is only guaranteed 1-byte aligned, so the parsed
// OODF buffer cxx hands us via `rust::Slice<const uint8_t>` is not
// guaranteed to be 8-aligned).  Rust's `slice::from_raw_parts<u64>` debug
// UB check enforces `ptr % alignof::<u64>() == 0`, which is what
// `wire_fixtures::mixed_delta_round_trips` tripped on. To avoid that, copy
// elements through an aligned `std::vector<uint64_t>` and then bulk-copy
// across the bridge. The intermediate copy is O(N) — same big-O as the
// previous per-element push_back loop — but the bridge cost drops from N
// to 1.
rust::Vec<uint64_t> to_rust_u64_vec(const ::flatbuffers::Vector<uint64_t>* v) {
    rust::Vec<uint64_t> out;
    if (v == nullptr) {
        return out;
    }
    const size_t size = v->size();
    if (size == 0) {
        return out;
    }
    // Reify into an aligned std::vector first so the bridge slice is
    // built from an 8-byte-aligned pointer (std::vector's allocator
    // returns memory aligned to at least alignof(uint64_t)).
    // `flatbuffers::Vector::Get(i)` returns a little-endian-decoded value
    // and is alignment-safe regardless of buffer alignment.
    std::vector<uint64_t> aligned;
    aligned.reserve(size);
    for (::flatbuffers::uoffset_t i = 0; i < size; ++i) {
        aligned.push_back(v->Get(i));
    }
    rust::Slice<const uint64_t> slice(aligned.data(), aligned.size());
    extend_u64_vec(out, slice);
    return out;
}

// Entry counts read by `probe_entry_counts` from a delta's vector headers.
struct EntryCounts {
    uint64_t struct_commands = 0;
    uint64_t set_fields = 0;
    uint64_t time_samples = 0;
};

// Entry-count probe: read the lengths of the delta's three entry vectors
// without walking any entry, so `parse_delta` can refuse an over-cap buffer
// with the counts before the full verifier runs.
//
// SECURITY: every byte this reads is first bounds-checked by the FlatBuffers
// library's own verify primitives, in the order the generated
// `Delta::Verify` uses them — `Verifier::VerifyOffset` for the root offset,
// `Table::VerifyTableStart` for the root table and its vtable,
// `Table::VerifyOffset` for each vector field's offset slot, and
// `Verifier::VerifyVector` for each vector's length word and extent. Only
// after those pass does it read a vtable entry, an offset or a length. It
// never follows an element offset, so no command, field or sample is
// touched. The probe uses its own throwaway `Verifier`; the full verifier
// that runs afterwards starts from fresh counters.
//
// Returns false — "no count", never an error — when any check fails or the
// two union vectors (`structCommands_type`, `structCommands`) are unpaired
// (one present without the other, or different lengths). The caller then
// falls through to the full verifier, so a buffer the probe cannot count
// keeps the outcome it would have had without the probe. A buffer whose
// headers pass, whose counts sum to over `kMaxDeltaEntries` (99,999) and
// whose elements are malformed is refused `TooManyTables` before the
// verifier would refuse it `VerifierFailed`; both are `INVALID_ARGUMENT`.
bool probe_entry_counts(const uint8_t* data, size_t size, EntryCounts* out) {
    using ::flatbuffers::Offset;
    using ::flatbuffers::Table;
    using ::flatbuffers::Vector;
    using Delta = OmniObjectDelta::Delta;

    ::flatbuffers::Verifier::Options opts;
    opts.max_depth = kVerifierMaxDepth;
    opts.max_tables = kVerifierMaxTables;
    ::flatbuffers::Verifier probe(data, size, opts);

    // Root offset: 4 readable, aligned bytes at 0, non-zero, pointing inside
    // the buffer. Returns 0 on any failure.
    const size_t root_offset = probe.VerifyOffset<::flatbuffers::uoffset_t>(0);
    if (root_offset == 0) {
        return false;
    }
    const auto* root = reinterpret_cast<const Table*>(data + root_offset);
    // Root table's vtable offset, and the whole vtable, inside the buffer.
    if (!root->VerifyTableStart(probe)) {
        return false;
    }

    // Each vector: its offset slot (if the vtable names one) inside the
    // buffer and pointing inside it, then its length word and full extent.
    // `GetPointer` returns null for an absent field; `VerifyVector(nullptr)`
    // is true, matching the generated verifier.
    if (!root->VerifyOffset(probe, Delta::VT_STRUCTCOMMANDS_TYPE)) {
        return false;
    }
    const auto* cmd_types =
        root->GetPointer<const Vector<uint8_t>*>(Delta::VT_STRUCTCOMMANDS_TYPE);
    if (!probe.VerifyVector(cmd_types)) {
        return false;
    }
    if (!root->VerifyOffset(probe, Delta::VT_STRUCTCOMMANDS)) {
        return false;
    }
    const auto* cmd_values =
        root->GetPointer<const Vector<Offset<void>>*>(Delta::VT_STRUCTCOMMANDS);
    if (!probe.VerifyVector(cmd_values)) {
        return false;
    }
    if (!root->VerifyOffset(probe, Delta::VT_SETFIELDS)) {
        return false;
    }
    const auto* fields = root->GetPointer<const Vector<Offset<OmniObjectDelta::SetField>>*>(
        Delta::VT_SETFIELDS);
    if (!probe.VerifyVector(fields)) {
        return false;
    }
    if (!root->VerifyOffset(probe, Delta::VT_TIMESAMPLES)) {
        return false;
    }
    const auto* samples = root->GetPointer<const Vector<Offset<OmniObjectDelta::TimeSample>>*>(
        Delta::VT_TIMESAMPLES);
    if (!probe.VerifyVector(samples)) {
        return false;
    }

    // The union's two vectors must pair up exactly as the generated
    // `VerifyStructCommandVector` requires; otherwise leave the verdict to it.
    if ((cmd_types == nullptr) != (cmd_values == nullptr)) {
        return false;
    }
    if (cmd_types != nullptr && cmd_types->size() != cmd_values->size()) {
        return false;
    }

    out->struct_commands = cmd_values != nullptr ? cmd_values->size() : 0;
    out->set_fields = fields != nullptr ? fields->size() : 0;
    out->time_samples = samples != nullptr ? samples->size() : 0;
    return true;
}

