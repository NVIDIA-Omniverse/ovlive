// C++ implementation of the OODF FFI surface.
//
// SECURITY INVARIANT. `parse_delta` ingests untrusted bytes from the network.
// The hardened verifier (`VerifyDeltaBuffer`, bounded by the Verifier::Options
// below) runs on every such buffer before any FlatBuffers accessor reads it.
// Beyond the size checks and the file-identifier check of the fixed 8-byte
// preamble, the one exception is the entry-count probe
// (`probe_entry_counts`), which runs just before the verifier to read the
// lengths of the root table's three entry vectors. It reads only the root
// offset, the root table's vtable, and the offset slots and length words of
// `structCommands_type`, `structCommands`, `setFields` and `timeSamples`,
// each after the library's own verify primitives have bounds-checked it, and
// it never follows an element offset. Adding any other read before the
// verifier, or raising the verifier's caps, needs a security review. The
// invariant is stated here and in SDD §8.2; `parse_delta`'s comment gives the
// order of its checks.

