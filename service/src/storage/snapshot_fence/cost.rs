/// `s1`, ms per item: the structural slow-path attempt is
/// `S(e, b) = F(e, b) + s1·max(e, S_MIN_ITEMS) + s0` (Spec SDD SR-11.1), AMR
/// model, and it must cover one attempt on AMR at every size the runtime
/// evaluates it at: the cold-start check's probe estimate and the fenced
/// read's measured size (the wait cap's, once a fence key stores one).
///
/// The method ([`S_REFIT_RESULTS`]): each point a whole attempt (WATCH, read,
/// plan, MULTI…EXEC) — Task 10's structural runs on this build plus one at or
/// above the cold-start cut-off's probe-bound items (about 4.7 M items), each
/// at its measured size, and the documented shapes (the flattened
/// Kitchen_set; ref-xform at 1,000, 5,000 and about 30,000 placed assets, each
/// one prim with a reference and four attributes; the 1,000-frame rig), each
/// at its probe estimate and its measured size — converted to AMR by the
/// larger of × 1.502323 and SDD §10.5's additive form, then the chord in AMR
/// space on `S − F` through the smallest point and the largest, `s0` raised by
/// the largest excess of any other point over that chord (here the flattened
/// Kitchen_set at its measured size, 842.3 ms, on the chord's intercept of
/// 1.7 ms: [`S_S0_MS`]), no scaling after. Past the largest point `S`
/// is a linear extrapolation; the method's extrapolation guard holds the
/// cut-off's probe-bound items at or below it, so beyond it `S` reaches only
/// `intent_ttl`, `reader_wait_max` and `key_linger`, whose `1.5·S` factor and
/// floors carry margin.
pub const S_S1_MS_PER_ITEM: f64 = -3.236_521_917_889_181e-4;

/// `s0`, ms: the intercept of `S(e, b)`'s `s1·max(e, S_MIN_ITEMS) + s0` term,
/// the safe-side envelope's ([`S_S1_MS_PER_ITEM`]).
pub const S_S0_MS: f64 = 844.020_864_450_644_2;

/// The fewest items `S(e, b)`'s structural term `s1·e + s0` is evaluated at:
/// the low end of the fit's valid range, its smallest point's items
/// (structural-2k at its measured size; [`S_REFIT_RESULTS`]).
///
/// Below it the chord is an extrapolation, so a smaller layer is charged the
/// structural term of one at this size (Spec SDD SR-11.4, decider design
/// revision of 2026-10-02); `F(e, b)` itself is still evaluated at the
/// layer's own size. `intent_ttl(L)`'s queue floor dominates there either
/// way.
pub const S_MIN_ITEMS: f64 = 18_415.0;

/// `A` near the ceiling, intercept, ms: one atomic read of `e` items costs
/// `A = c0 + c1·e` on Kitchen_set's ray (the restricted x(15) line the shipped
/// ceiling was solved with), AMR model, evaluated at the configured item
/// ceiling to give `A(e_c, b_c)`.
///
/// Report § Platform models and the coefficient set code uses ("Which `A`":
/// items only, so the byte ceiling does not enter); full precision from
/// `raw/task1-fence-inputs/fence_inputs.txt` part 12.
pub const A_C0_MS: f64 = 1.791_741_854_744_38;

/// `A` near the ceiling, per-item term, ms per item. Same source as
/// [`A_C0_MS`]; 39.328 ms at the shipped ceiling of 37,554 items.
pub const A_C1_MS_PER_ITEM: f64 = 9.995_236_514_224_16e-4;

/// `rtt99`, ms: the p99 round trip of a small script call, AMR (client-side).
///
/// Report § Platform models and the coefficient set code uses (§ Inputs from
/// Epics 1 and 2: `rtt99`); full precision from
/// `raw/task1-fence-inputs/fence_inputs.txt` part 12.
pub const RTT99_MS: f64 = 1.391_506_986_692_547_8;

/// `R_design`: the replica count the defaults are computed for, the chart's
/// default `autoscaling.maxReplicas` (Spec SDD SR-11.1). Report § Inputs from Epics 1 and 2
/// (`W0_shard`; `W_wave`).
pub const R_DESIGN: f64 = 10.0;

/// `D`, ms: the product owner's per-read bound, one atomic read may block its
/// shard for at most this long (Spec SDD SR-11.1). Report § Inputs from Epics
/// 1 and 2 (`W0_shard`; `W_wave`).
pub const D_MS: f64 = 50.0;

/// `W_wave` = `R_design × D`, ms: the per-wave writer-delay allowance (Spec
/// SDD SR-11.1), derived rather than a constant of its own. 500 ms; report
/// § Inputs from Epics 1 and 2.
pub const W_WAVE_MS: f64 = R_DESIGN * D_MS;

/// The bytes per item used as `bpi` for a layer no fenced read has recorded a
/// size for (Spec SDD SR-11.1): the size of an early-out `TOO_LARGE` answer,
/// which reports items only, is `items × bpi` until the layer's first fenced
/// read records its measured `bpi` on the fence key.
///
/// 16.1, the real-id ray: a Kitchen_set live layer whose section ids are real,
/// full-width random 64-bit integers, as every client allocates them — the
/// same ray as the atomic-read byte ceiling
/// (`config::SNAPSHOT_ATOMIC_READ_MAX_BYTES_DEFAULT`), recorded together in
/// `docs-internal/validation/real-id-byte-ceiling-20261006/derivation.json`
/// (`real_id_bytes_per_item`). It replaced 11.981, Epic 1's short-id probe
/// layer's ray, which under-sized the first fenced flight's memory grant of a
/// real layer by about a quarter until the post-read adjust. Only that size
/// estimate moves: `F`'s per-byte term changes the expected hold by under
/// 0.05 % at 10× the item ceiling, `S` has no byte term, and the fan-out
/// window and round-1 bounds are per command and per member, not per byte.
pub const FITTED_BYTES_PER_ITEM: f64 = 16.1;

/// How many times one fenced read is attempted before a `BROKEN` release
/// becomes a transient error (`UNAVAILABLE` for catch-up, a skipped tick for
/// the checkpoint). A retry count, not a time limit (Spec SDD SR-5.3).
pub const FENCE_READ_ATTEMPTS: u32 = 3;

/// The number of coefficient arguments every fence script takes, in the order
/// [`FenceCoefficients::script_argv`] emits them: `f0`, `f1`, `f2`, `s1`, `s0`,
/// `ceiling_read`, `rtt99`, `w_wave`, `s_min_items`.
pub const FENCE_COEFFICIENT_ARGC: usize = 9;

/// A layer's size `L = (e, b)` (Spec SDD SR-11.1): `items` is the SR-1.2 item
/// count, `bytes` the reply bytes of a full read.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct LayerSize {
    /// `e`, items.
    pub items: u64,
    /// `b`, reply bytes.
    pub bytes: u64,
}

impl LayerSize {
    /// Bytes per item, or `None` for an empty layer.
    pub fn bytes_per_item(&self) -> Option<f64> {
        (self.items > 0).then(|| self.bytes as f64 / self.items as f64)
    }

    /// Size a layer from its atomic read's `TOO_LARGE` answer (Spec SDD
    /// SR-11.1).
    ///
    /// - `e` is the answer's item bound. On a mid-read abort it is
    ///   `max(bound, item tally)`: the bound is the safe figure, and a tally
    ///   that passed it (the item-tally anomaly) is larger still. The tally alone
    ///   is partial — the script stopped at the crossing — and would under-size
    ///   the layer.
    /// - `b`, on a mid-read abort, is the byte tally scaled by `e ÷ item tally`:
    ///   the bytes per item measured so far, applied to the whole layer. On an
    ///   early-out (or a mid-read abort with no item tallied) it is `e × bpi`,
    ///   with `recorded_bpi` — the `bpi` the fence key stored at the layer's
    ///   last fenced read — when the caller has one, and
    ///   [`FITTED_BYTES_PER_ITEM`] otherwise. A recorded value that is not a
    ///   positive finite number is ignored.
    ///
    /// Bytes are rounded up, the safe direction for every limit sized from
    /// them.
    pub fn from_too_large(answer: &SnapshotTooLarge, recorded_bpi: Option<f64>) -> Self {
        let bpi = recorded_bpi
            .filter(|v| v.is_finite() && *v > 0.0)
            .unwrap_or(FITTED_BYTES_PER_ITEM);
        match answer.at {
            SnapshotTooLargeAt::MidRead {
                item_tally,
                byte_tally,
                ..
            } => {
                let items = answer.item_bound.max(item_tally);
                let bytes = if item_tally > 0 {
                    scale_up(byte_tally, items, item_tally)
                } else {
                    ceil_to_u64(items as f64 * bpi)
                };
                LayerSize { items, bytes }
            }
            SnapshotTooLargeAt::EarlyOut => {
                let items = answer.item_bound;
                LayerSize {
                    items,
                    bytes: ceil_to_u64(items as f64 * bpi),
                }
            }
        }
    }
}

/// `ceil(value × numerator ÷ denominator)` in integer arithmetic, saturating.
/// `denominator` is non-zero at the only call site.
fn scale_up(value: u64, numerator: u64, denominator: u64) -> u64 {
    let scaled = (u128::from(value) * u128::from(numerator)).div_ceil(u128::from(denominator));
    u64::try_from(scaled).unwrap_or(u64::MAX)
}

/// Round a non-negative byte estimate up to a whole byte, saturating.
fn ceil_to_u64(value: f64) -> u64 {
    // `as` saturates for out-of-range floats and maps NaN to 0; the inputs here
    // are a finite item count times a positive finite bpi.
    value.ceil() as u64
}

/// The fitted coefficients every fence limit is computed from, evaluated for
/// one configured atomic-read ceiling.
///
/// Built by [`Self::recorded`]; the fields are public so a test can evaluate
/// the formulas on another coefficient set (the report's sandbox model, say)
/// and compare them with the recorded tables.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct FenceCoefficients {
    /// `F` intercept, ms.
    pub f0_ms: f64,
    /// `F` per-item term, ms per item.
    pub f1_ms_per_item: f64,
    /// `F` per-byte term, ms per byte.
    pub f2_ms_per_byte: f64,
    /// `S − F` per-item term, ms per item.
    pub s1_ms_per_item: f64,
    /// `S − F` intercept, ms.
    pub s0_ms: f64,
    /// `A(e_c, b_c)`, ms: one atomic read of a ceiling-sized layer at the
    /// configured item ceiling.
    pub ceiling_read_ms: f64,
    /// `rtt99`, ms.
    pub rtt99_ms: f64,
    /// `W_wave`, ms.
    pub w_wave_ms: f64,
    /// The fewest items the structural term `s1·e + s0` is evaluated at
    /// ([`S_MIN_ITEMS`]).
    pub s_min_items: f64,
}

impl FenceCoefficients {
    /// The recorded (AMR) coefficient set, with `A(e_c, b_c)` evaluated at
    /// `item_ceiling`, the configured `LIVE_EDIT_SNAPSHOT_ATOMIC_READ_MAX_ITEMS`
    /// — so an operator who lowers the ceiling also lowers `min_gap` and `Q`.
    pub fn recorded(item_ceiling: u64) -> Self {
        FenceCoefficients {
            f0_ms: F_F0_MS,
            f1_ms_per_item: F_F1_MS_PER_ITEM,
            f2_ms_per_byte: F_F2_MS_PER_BYTE,
            s1_ms_per_item: S_S1_MS_PER_ITEM,
            s0_ms: S_S0_MS,
            ceiling_read_ms: A_C0_MS + A_C1_MS_PER_ITEM * item_ceiling as f64,
            rtt99_ms: RTT99_MS,
            w_wave_ms: W_WAVE_MS,
            s_min_items: S_MIN_ITEMS,
        }
    }

    /// The coefficient block every fence script takes in `ARGV`, in the order
    /// the scripts read it (see [`FENCE_COEFFICIENT_ARGC`]).
    ///
    /// Rendered with `f64`'s `Display`, the shortest decimal that parses back
    /// to the same value, so the scripts' `tonumber` sees exactly the
    /// coefficients [`Self::timing`] uses.
    pub fn script_argv(&self) -> [String; FENCE_COEFFICIENT_ARGC] {
        [
            self.f0_ms.to_string(),
            self.f1_ms_per_item.to_string(),
            self.f2_ms_per_byte.to_string(),
            self.s1_ms_per_item.to_string(),
            self.s0_ms.to_string(),
            self.ceiling_read_ms.to_string(),
            self.rtt99_ms.to_string(),
            self.w_wave_ms.to_string(),
            self.s_min_items.to_string(),
        ]
    }

    /// `Q = W_wave + A(e_c, b_c)`, ms: the shard-level delay one join wave may
    /// add, plus one fan-out window. Independent of the layer's size.
    pub fn q_ms(&self) -> f64 {
        self.w_wave_ms + self.ceiling_read_ms
    }

    /// `poll = join_window = 2·(rtt99 + Q)`, ms — [`FenceTiming::poll_ms`],
    /// which depends on no layer size. A writer refused `FENCED` sleeps
    /// `min(retry_after, poll)` (Spec SDD SR-5.4, SR-11.4) without knowing
    /// the layer's size, so it reads the step from here.
    pub fn poll_ms(&self) -> f64 {
        2.0 * (self.rtt99_ms + self.q_ms())
    }

    /// Every SR-11.4 / SR-11.5 limit for a layer of size `size`.
    ///
    /// The fence scripts evaluate these same expressions in this same order
    /// (see the module docs); a change here is a change to every
    /// `snapshot_fence_*.lua` / `snapshot_intent_*.lua` script's `timing`
    /// function too.
    pub fn timing(&self, size: LayerSize) -> FenceTiming {
        let e = size.items as f64;
        let b = size.bytes as f64;
        // hold(L) = F(e, b), the expected epoch.
        let hold = self.f0_ms + self.f1_ms_per_item * e + self.f2_ms_per_byte * b;
        // Q = W_wave + A(e_c, b_c): the shard-level delay one join wave may
        // add, plus one fan-out window. Every floor below sits behind it.
        let q = self.q_ms();
        let rtt_q = self.rtt99_ms + q;
        let lease = (4.0 * rtt_q).max(hold / 4.0);
        // `poll_ms()` evaluates the same `2·(rtt99 + Q)`, in the same order.
        let join_window = 2.0 * rtt_q;
        let poll = join_window;
        let min_gap = self.ceiling_read_ms;
        // S(e, b) = F(e, b) + s1·e + s0, with the structural term evaluated no
        // lower than the low end of the chord's fitted range (S_MIN_ITEMS):
        // below it the chord is an extrapolation, so it is not used. The term
        // can be negative there (`s1·S_MIN_ITEMS + s0 < 0` on a fit whose
        // attempt costs less than its fenced read at that size), and then S
        // falls below zero for a layer whose hold is short; S is used only
        // through intent_ttl's max below, whose queue floor then decides, and
        // through the structural cache's deadline reserve, which takes it at
        // no less than zero.
        let structural_attempt = hold + self.s1_ms_per_item * e.max(self.s_min_items) + self.s0_ms;
        // intent_ttl(L) = max(4·(rtt99 + Q), 1.5·S(e, b)): the same floor as
        // the lease, so an intent and its renewals (every intent_ttl/4) stay
        // longer than the queue a script call can wait behind, whatever the
        // layer's structural cost.
        let intent_ttl = (4.0 * rtt_q).max(1.5 * structural_attempt);
        let epoch = hold.max(lease) + join_window;
        let reader_wait_max = 3.0 * (epoch + epoch.max(min_gap) + intent_ttl + poll) + hold;
        let key_linger = 20.0 * (hold + hold.max(min_gap) + intent_ttl);
        FenceTiming {
            hold_ms: hold,
            q_ms: q,
            lease_ms: lease,
            join_window_ms: join_window,
            poll_ms: poll,
            min_gap_ms: min_gap,
            structural_attempt_ms: structural_attempt,
            intent_ttl_ms: intent_ttl,
            epoch_ms: epoch,
            reader_wait_max_ms: reader_wait_max,
            key_linger_ms: key_linger,
        }
    }
}

/// Every fence limit for one layer size (Spec SDD SR-11.4, SR-11.5), in
/// milliseconds. [`ms_to_duration`] turns one into a `Duration`.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct FenceTiming {
    /// `hold(L) = F(e, b)`: the expected epoch, one fenced read's wall time.
    pub hold_ms: f64,
    /// `Q = W_wave + A(e_c, b_c)`: the shard work a script call can queue
    /// behind.
    pub q_ms: f64,
    /// `lease(L) = max(4·(rtt99 + Q), hold(L)/4)`: a fenced reader's lease,
    /// renewed every `lease(L)/4` ([`Self::renew_interval_ms`]).
    pub lease_ms: f64,
    /// `join_window = 2·(rtt99 + Q)`: how long after an epoch starts a reader
    /// may still join it.
    pub join_window_ms: f64,
    /// `poll = join_window`: the longest step a waiting reader or a fenced
    /// writer sleeps (`min(retry_after, poll)`).
    pub poll_ms: f64,
    /// `min_gap = A(e_ceiling, b_ceiling)`: the shortest writers' gap after an
    /// epoch.
    pub min_gap_ms: f64,
    /// `S(e, b) = F(e, b) + s1·max(e, S_MIN_ITEMS) + s0`: the structural
    /// slow-path attempt's modelled time. Not a duration on its own: when the
    /// structural term is negative at [`S_MIN_ITEMS`] it falls below zero for
    /// a fenced layer whose hold is short, and it is consumed only through
    /// `intent_ttl(L)`'s `max` with the queue floor and the structural cache's
    /// deadline reserve, taken at no less than zero.
    pub structural_attempt_ms: f64,
    /// `intent_ttl(L) = max(4·(rtt99 + Q), 1.5·S(e, b))`: a writer intent's
    /// lifetime, renewed every `intent_ttl(L)/4`
    /// ([`Self::intent_renew_interval_ms`]); readers honour intents until
    /// `gap_until + intent_ttl(L)`.
    pub intent_ttl_ms: f64,
    /// `epoch(L) = max(hold(L), lease(L)) + join_window`: the longest an epoch
    /// can last (a crashed holder, or joiners extending it).
    pub epoch_ms: f64,
    /// `reader_wait_max(L) = 3·(epoch(L) + max(epoch(L), min_gap) +
    /// intent_ttl(L) + poll) + hold(L)`: the safety cap on a catch-up waiter's
    /// wait for its flight's fenced read, and on the checkpoint's fence wait
    /// ([`Self::checkpoint_fence_wait_ms`]).
    pub reader_wait_max_ms: f64,
    /// `key_linger(L) = 20·(hold(L) + max(hold(L), min_gap) + intent_ttl(L))`:
    /// how long a fence key outlives its latest deadline or gap.
    pub key_linger_ms: f64,
}

impl FenceTiming {
    /// The lease renewal period, `lease(L) / 4`.
    pub fn renew_interval_ms(&self) -> f64 {
        self.lease_ms / 4.0
    }

    /// The intent renewal period, `intent_ttl(L) / 4`.
    pub fn intent_renew_interval_ms(&self) -> f64 {
        self.intent_ttl_ms / 4.0
    }

    /// The longest a fenced checkpoint read waits for the fence:
    /// `reader_wait_max(L)`, the same cap as catch-up (Spec SDD SR-11.5).
    pub fn checkpoint_fence_wait_ms(&self) -> f64 {
        self.reader_wait_max_ms
    }
}

/// A limit in milliseconds as a `Duration`. Negative or non-finite inputs map
/// to zero rather than panicking. Every limit [`FenceCoefficients::timing`]
/// derives is non-negative under a valid coefficient set except
/// [`FenceTiming::structural_attempt_ms`], which can fall below zero for a
/// fenced layer whose hold is short and is consumed through
/// `intent_ttl(L)`'s `max` with the queue floor, and as a duration only once
/// clamped at zero (the structural cache's deadline reserve).
pub fn ms_to_duration(ms: f64) -> Duration {
    Duration::try_from_secs_f64(ms / 1_000.0).unwrap_or(Duration::ZERO)
}

