//! The fence cost model: every per-layer fence, writer-protection and
//! checkpoint-wait limit as a function of the layer's size (Spec SDD SR-5.7,
//! SR-11.1, SR-11.4, SR-11.5).
//!
//! No limit here is a hand-picked constant. Only the fitted coefficients are
//! constants, each citing where it was recorded: `F` in the Task 10 section
//! of the Epic 3 validation report
//! (`docs-internal/validation/fenced-snapshot-reads-20261002/report.md`,
//! re-fitted on the implemented fenced reader; full precision in that
//! folder's `raw/task10-results/results.json`), `S` re-fitted on the
//! structural attempt as it now reads, in AMR space ([`S_REFIT_RESULTS`];
//! the method at [`S_S1_MS_PER_ITEM`]), the rest in the Epic 3 report's
//! `## Recorded inputs (Task 1)`; every limit is computed from them and the
//! layer size `L = (e, b)` at run time.
//!
//! # One model, two evaluators
//!
//! The fence scripts compute the same functions server-side, from the layer
//! size stored in the fence key and the coefficients the caller passes in
//! `ARGV` ([`FenceCoefficients::script_argv`]), because the stored size wins
//! over any caller's estimate and every reader of one epoch must derive the
//! same deadlines. Callers therefore compute every limit they need through
//! [`FenceCoefficients::timing`] and pass the scripts the same coefficient
//! block, never a value of their own. The scripts evaluate the formulas in the
//! order [`FenceCoefficients::timing`] does and round each duration they store
//! or return up to a whole millisecond.
//!
//! # The coefficient set is the AMR model
//!
//! Every cost term but `S`'s is the sandbox fit scaled by the measured AMR /
//! sandbox cost ratio (1.502323), with AMR's own `rtt99`: the shipped
//! atomic-read ceiling was derived for AMR, the chart carries no per-platform
//! default, and the AMR value is the larger one in every function here (report
//! § Platform models and the coefficient set code uses). `S`'s fit converts
//! each point to AMR by the larger of that ratio and SDD §10.5's additive form
//! (localhost time + round trips × 1.3 ms + the store's time × 0.502 + 0.69 µs
//! per plain command) and fits in AMR space, because the structural attempt's
//! read waits on its serial window round trips, which a ratio taken on a
//! CPU-bound wall underprices ([`S_S1_MS_PER_ITEM`]).

